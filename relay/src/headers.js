// Site security headers. One source for two paths: scripts/build-web.mjs writes them to
// relay/public/_headers (assets served directly by the alias worker), and the relay adds them
// to assets served through env.ASSETS. The login token, phone device secret, and Codespaces token
// live in localStorage: a strict CSP limits XSS impact (no inline / third-party scripts).
// connect-src only to the relay itself ('self' + the relay's wss:// hosts): XSS can't open a WebSocket to an
// attacker's server to exfiltrate the device secret. `hosts` = the relay's public hosts (no scheme).
/** @param {string[]} [hosts] */
export function csp(hosts = []) {
  return [
    "default-src 'self'",
    "script-src 'self'",
    // Style attributes are used by the UI (sheet position, per-element CSS variables).
    "style-src 'self' 'unsafe-inline'",
    // Preview screenshots & attached images are sent as data: URLs.
    "img-src 'self' data: blob:",
    "font-src 'self'",
    // api.github.com: Codespaces runner from the phone.
    ["connect-src 'self'", ...[...new Set(hosts.filter(Boolean))].map((h) => 'wss://' + h), 'https://api.github.com'].join(' '),
    "worker-src 'self'",
    "manifest-src 'self'",
    "object-src 'none'",
    "base-uri 'none'",
    "frame-ancestors 'none'",
    "form-action 'self'",
  ].join('; ');
}
export const CSP = csp();

/** @param {string[]} [hosts] */
export const securityHeaders = (hosts) => ({
  'content-security-policy': csp(hosts),
  'x-content-type-options': 'nosniff',
  'referrer-policy': 'no-referrer',
  'x-frame-options': 'DENY',
});
export const SECURITY_HEADERS = securityHeaders();

// HTML pages generated by the relay (login, confirmation): no scripts at all.
export const PAGE_HEADERS = {
  ...SECURITY_HEADERS,
  'content-security-policy': "default-src 'none'; style-src 'unsafe-inline'; form-action 'self'; frame-ancestors 'none'; base-uri 'none'",
  'cache-control': 'no-store',
};
